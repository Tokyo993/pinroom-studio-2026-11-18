// Optional integration checks. Install Playwright locally before running this file.
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch(process.env.BROWSER_EXECUTABLE?{headless:true,executablePath:process.env.BROWSER_EXECUTABLE}:{headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:390,height:844}});
const runId=Date.now().toString().slice(-6);
const checks=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.BASE_URL||'http://127.0.0.1:4173';
try{
  await mkdir('work',{recursive:true});
  await page.goto(base);
  assert.equal((await page.request.get(base+'/api/library')).status(),401);
  await page.locator('.mobile-nav [data-action="account"]').click();
  await page.locator('.account-signin').click();
  await page.waitForURL(base+'/');
  await page.waitForFunction(()=>document.querySelector('.avatar')?.classList.contains('signed-in'));
  checks.push('guest denied and local sign-in succeeds');
  await page.locator('.pin-card').first().waitFor({timeout:25000});
  await page.waitForFunction(()=>document.querySelector('.pin-picture img')?.naturalWidth>0);
  assert.ok(await page.locator('.pin-card').count());checks.push('real external image feed');
  const id=await page.locator('.pin-save').first().getAttribute('data-id');
  await page.locator('.pin-save').first().click();await page.locator('#board-name').fill('Browser QA '+runId);await page.locator('#board-form button').click();await page.locator('#dialog').waitFor({state:'hidden'});
  await page.locator('.mobile-nav [data-nav="boards"]').click();await page.locator('.board-card').filter({hasText:'Browser QA '+runId}).click();
  await page.reload();await page.locator('.pin-card').waitFor();assert.equal(await page.locator('.pin-card').count(),1);checks.push('board persists after reload');
  await page.locator('.mobile-nav [data-action="focus-search"]').click();await page.locator('#search').fill('sunflower');await page.locator('#search').press('Enter');await page.locator('.pin-card').first().waitFor({timeout:25000});assert.match(await page.locator('h1').innerText(),/sunflower/);checks.push('search from board route');
  await page.goto(base+'/#/edit/'+id);await page.locator('[data-action="export"]:enabled').waitFor({timeout:25000});
  const original=await page.locator('#canvas').evaluate(c=>c.toDataURL());await page.locator('[data-action="flip"]').click();
  const edited=await page.locator('#canvas').evaluate(c=>c.toDataURL());assert.notEqual(edited,original);await page.locator('[data-action="undo"]').click();assert.equal(await page.locator('#canvas').evaluate(c=>c.toDataURL()),original);checks.push('pixel-changing reflection and undo');
  await page.locator('[data-action="edit-tab"][data-value="crop"]').click();await page.locator('[data-action="ratio"][data-value="1:1"]').click();const dims=await page.locator('#canvas').evaluate(c=>[c.width,c.height]);assert.equal(dims[0],dims[1]);checks.push('square crop');
  const downloadEvent=page.waitForEvent('download');await page.locator('[data-action="export"]').click();const download=await downloadEvent;assert.equal(await download.failure(),null);checks.push('PNG download');
  await page.locator('[data-action="save-edit"]').click();await page.locator('.board-option').filter({hasText:'Browser QA '+runId}).click();await page.locator('#dialog').waitFor({state:'hidden'});
  await page.locator('.editor-heading a').click();await page.locator('.mobile-nav [data-nav="boards"]').click();await page.locator('.board-card').filter({hasText:'Browser QA '+runId}).click();assert.equal(await page.locator('.pin-card').count(),2);checks.push('separate derivative and original');
  const privateImage=page.locator('.pin-picture img[src^="/api/assets/"]');
  await privateImage.waitFor();
  await privateImage.evaluate(img=>img.loading='eager');
  await page.waitForFunction(()=>document.querySelector('img[src^="/api/assets/"]')?.naturalWidth>0);
  const privateUrl=await privateImage.getAttribute('src');
  assert.equal((await page.request.get(base+privateUrl)).status(),200);
  checks.push('private R2 image displays for owner');
  await page.setViewportSize({width:320,height:740});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);checks.push('320px layout');
  await page.locator('.mobile-nav [data-action="account"]').click();
  await page.locator('.account-person').waitFor();
  await page.screenshot({path:'work/auth-profile-mobile.png'});
  await page.locator('[data-action="sign-out"]').click();
  await page.waitForFunction(()=>!document.querySelector('.avatar')?.classList.contains('signed-in'));
  assert.equal((await page.request.get(base+'/api/library')).status(),401);
  assert.equal((await page.request.get(base+privateUrl)).status(),401);
  checks.push('logout denies private library and image access');
  assert.deepEqual(errors,[]);checks.push('no uncaught errors');
  await mkdir('work',{recursive:true});await writeFile('work/browser-report.json',JSON.stringify({checkedAt:new Date().toISOString(),checks,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
}finally{await browser.close();}
